package com.aicouncil.app;

/**
 * Pure prompt builders for mutual critique and coordinator synthesis.
 * Network and UI stay outside this class.
 */
public final class CouncilAnalysisPolicy {
    private CouncilAnalysisPolicy() {}

    public static String buildCritiquePrompt(String task, String ownAnswer, String peerAnswer, int reviewerNumber) {
        int n = reviewerNumber <= 1 ? 1 : 2;
        int peer = n == 1 ? 2 : 1;
        return "Ты ИИ №" + n + " в AI Council. Проведи взаимную критику ответа ИИ №" + peer + ".\n"
                + "Правила:\n"
                + "- Не защищай свой предыдущий ответ автоматически.\n"
                + "- Отдели подтверждённые ошибки от гипотез.\n"
                + "- Если данных недостаточно — так и скажи.\n"
                + "- Не выдумывай источники.\n\n"
                + "Структура ответа:\n"
                + "1) Сильные стороны ответа ИИ №" + peer + "\n"
                + "2) Ошибки и слабые места\n"
                + "3) Что осталось неясным\n"
                + "4) Уточнённый вариант (кратко), если уместно\n\n"
                + "ИСХОДНАЯ ЗАДАЧА:\n" + safe(task) + "\n\n"
                + "ТВОЙ ОТВЕТ:\n" + safe(ownAnswer) + "\n\n"
                + "ОТВЕТ ИИ №" + peer + " ДЛЯ КРИТИКИ:\n" + safe(peerAnswer);
    }

    public static String coordinatorStructureRules() {
        return "Используй следующую структуру с короткими, содержательными разделами:\n"
                + "1. ОБЩИЙ ВЫВОД — прямой ответ на задачу в 1–3 предложениях.\n"
                + "2. ГДЕ ЭКСПЕРТЫ СОГЛАСНЫ — только содержательные совпадения; если согласия нет, скажи об этом.\n"
                + "3. РАЗНОГЛАСИЯ — для каждого важного пункта: позиция ИИ №1, позиция ИИ №2, суть конфликта и какие данные помогли бы.\n"
                + "4. ДОПУЩЕНИЯ И ПРОБЕЛЫ — скрытые предпосылки и недостающие входные данные.\n"
                + "5. ПРОВЕРКА РАССУЖДЕНИЙ — логика, формулы, арифметика по тексту; отделяй найденную ошибку от подозрения.\n"
                + "6. ЧТО НЕ ПРОВЕРЕНО — факты, которым нужны внешние источники или практика.\n"
                + "7. РЕКОМЕНДАЦИЯ — практический итог, уверенность (высокий/средний/низкий) и следующий шаг.\n"
                + "8. ОСНОВАНИЯ — для важных выводов: источник, расчёт, данные задачи или предположение модели.\n"
                + "9. УВЕРЕННОСТЬ И РИСКИ — одна строка: итоговая уверенность и главный риск ошибки.\n";
    }

    public static String coordinatorEvidenceRules() {
        return "Требования к доказательности: явно отделяй проверяемые факты от выводов модели; "
                + "не выдумывай URL, цитаты и документы; совпадение моделей — не независимое доказательство; "
                + "если один ответ — ошибка API, не анализируй его как позицию эксперта.\n";
    }

    public static String buildCoordinatorOpening() {
        return "Ты независимый координатор AI Council. Отвечай на языке исходной задачи. "
                + "Не считай совпадение ответов доказательством и не выбирай вывод по большинству голосов. "
                + "Сравнивай конкретные утверждения, а не общий тон ответов.\n\n"
                + coordinatorStructureRules() + "\n"
                + coordinatorEvidenceRules();
    }

    private static String safe(String s) {
        return s == null ? "" : s;
    }
}
